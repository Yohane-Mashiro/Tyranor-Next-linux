class Translator:
    def __init__(self, language: str = "zh_CN"):
        self.language = language if language in TRANSLATIONS else "zh_CN"

    def set_language(self, language: str) -> None:
        self.language = language if language in TRANSLATIONS else "zh_CN"

    def text(self, key: str, **values: object) -> str:
        table = TRANSLATIONS.get(self.language) or {}
        fallback = TRANSLATIONS["en"]
        value = table.get(key) or fallback.get(key) or TRANSLATIONS["zh_CN"].get(key) or key
        try:
            return value.format(**values)
        except (KeyError, ValueError):
            return value


def resolve_language(value: str) -> str:
    if value != "system":
        return value if value in TRANSLATIONS else "zh_CN"
    language = (os.environ.get("LC_ALL") or os.environ.get("LC_MESSAGES") or os.environ.get("LANG") or "").lower()
    if language.startswith("ja"):
        return "ja"
    if language.startswith(("en", "c")):
        return "en"
    return "zh_CN"
